export const getCompanyLogo = (name: string, className?: string): React.ReactNode => {
  const lower = name.toLowerCase();
  if (lower.includes('flutterwave')) return <FlutterwaveIcon className={className} />;
  if (lower.includes('chowdeck')) return <ChowdeckIcon className={className} />;
  if (lower.includes('paystack') || lower.includes('payflow')) return <PaystackIcon className={className} />;
  if (lower.includes('moniepoint')) return <MoniepointIcon className={className} />;
  if (lower.includes('piggy') || lower.includes('piggyvest')) return <PiggyVestIcon className={className} />;
  if (lower.includes('eden')) return <EdenLifeIcon className={className} />;
  if (lower.includes('kuda')) return <KudaIcon className={className} />;
  if (lower.includes('andela')) return <AndelaIcon className={className} />;
  if (lower.includes('combinator') || lower.includes('yc')) return <YCombinatorIcon className={className} />;
  if (lower.includes('techstars')) return <TechstarsIcon className={className} />;
  if (lower.includes('future africa')) return <FutureAfricaIcon className={className} />;
  if (lower.includes('ventures platform')) return <VenturesPlatformIcon className={className} />;
  if (lower.includes('google')) return <GoogleStartupsIcon className={className} />;
  
  // Default fallback if unknown company name
  return (
    <svg viewBox="0 0 24 24" className={className || "w-5 h-5 shrink-0"} fill="none" xmlns="http://www.w3.org/2000/svg">
      <rect width="24" height="24" rx="6" fill="#18181B" />
      <path d="M12 6L18 10V18H6V10L12 6Z" stroke="#E2E8F0" strokeWidth="2" strokeLinejoin="round" />
    </svg>
  );
};
